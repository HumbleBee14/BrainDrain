const API_URL = process.env.NEXT_PUBLIC_API_URL || "http://localhost:8000";

const DEFAULT_TIMEOUT_MS = 30_000;
// Deploy blocks on a warmup request that waits out a scale-to-zero GPU boot.
const GPU_COLDSTART_TIMEOUT_MS = 600_000;
const MAX_RETRIES = 3;
const BASE_BACKOFF_MS = 500;

interface ApiError {
  error: {
    code: string;
    message: string;
  };
}

export class ApiClientError extends Error {
  code: string;
  status: number;

  constructor(status: number, body: ApiError) {
    super(body.error.message);
    this.code = body.error.code;
    this.status = status;
  }
}

/**
 * Parses an error response body into the ApiError envelope.
 *
 * Not every error response is JSON: a text/plain 400 from the API, or an HTML
 * 502 from a proxy/load balancer, would make `res.json()` throw a SyntaxError
 * that masks the real HTTP error and surfaces as a confusing toast. Guard on
 * the Content-Type header — only parse JSON when the body actually is JSON —
 * and otherwise fall back to the raw text / status line. Genuine JSON error
 * envelopes keep their original shape and behavior.
 */
async function parseErrorBody(res: Response): Promise<ApiError> {
  const contentType = res.headers.get("content-type") ?? "";
  const fallbackMessage =
    res.statusText || `Request failed with status ${res.status}`;

  if (contentType.includes("application/json")) {
    try {
      const parsed = (await res.json()) as Partial<ApiError> | null;
      if (
        parsed &&
        typeof parsed === "object" &&
        parsed.error &&
        typeof parsed.error.message === "string"
      ) {
        return parsed as ApiError;
      }
    } catch {
      // Claimed to be JSON but failed to parse — fall through to status line.
    }
    return { error: { code: "http_error", message: fallbackMessage } };
  }

  // Non-JSON body (text/plain, HTML from a proxy, empty, …).
  if (contentType.includes("text/plain")) {
    try {
      const text = (await res.text()).trim();
      if (text) {
        return { error: { code: "http_error", message: text.slice(0, 500) } };
      }
    } catch {
      // Body unavailable — fall through to the status line.
    }
  }

  return { error: { code: "http_error", message: fallbackMessage } };
}

/**
 * Turns a raw DOMException ("signal is aborted without reason") into something a
 * user can act on, distinguishing our own timeout from a caller cancellation.
 */
function normalizeAbortError(
  error: unknown,
  timeoutMs: number,
  callerSignal?: AbortSignal | null,
): unknown {
  const isAbort =
    error instanceof DOMException && error.name === "AbortError";
  if (!isAbort) return error;
  if (callerSignal?.aborted) return error;

  return new ApiClientError(408, {
    error: {
      code: "timeout",
      message: `Request timed out after ${Math.round(timeoutMs / 1000)}s. If a GPU was starting from cold, it may still be finishing — reload in a minute.`,
    },
  });
}

function isRetryable(error: unknown): boolean {
  if (error instanceof ApiClientError) {
    return error.status >= 500;
  }
  // Only retry on network errors (TypeError). AbortError means timeout —
  // retrying timed-out requests can cause duplicate mutations server-side.
  return error instanceof TypeError;
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Wraps fetch with a timeout (via AbortController) and retry logic
 * for transient failures (network errors, 5xx responses).
 *
 * Retries up to MAX_RETRIES times with exponential backoff.
 * Non-retryable errors (4xx, known client errors) are thrown immediately.
 */
async function fetchWithRetry(
  url: string,
  init?: RequestInit,
  timeoutMs: number = DEFAULT_TIMEOUT_MS,
): Promise<Response> {
  let lastError: unknown;

  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), timeoutMs);

    if (init?.signal) {
      init.signal.addEventListener("abort", () => controller.abort(), {
        once: true,
      });
    }

    try {
      const res = await fetch(url, { ...init, signal: controller.signal });

      if (res.status >= 500 && attempt < MAX_RETRIES) {
        lastError = new ApiClientError(res.status, {
          error: {
            code: "server_error",
            message: `Server returned ${res.status}`,
          },
        });
        await sleep(BASE_BACKOFF_MS * 2 ** attempt);
        continue;
      }

      return res;
    } catch (error) {
      lastError = normalizeAbortError(error, timeoutMs, init?.signal);

      if (!isRetryable(error) || attempt >= MAX_RETRIES) {
        throw lastError;
      }

      await sleep(BASE_BACKOFF_MS * 2 ** attempt);
    } finally {
      clearTimeout(timeoutId);
    }
  }

  throw lastError;
}

/**
 * Typed API client for the Platform Rust backend.
 *
 * Automatically includes the Clerk session token in requests.
 * All methods return typed responses matching the Rust DTOs.
 */
async function request<T>(
  path: string,
  options?: RequestInit & { token?: string; timeoutMs?: number },
): Promise<T> {
  const { token, timeoutMs, ...fetchOptions } = options || {};

  const headers: Record<string, string> = {
    ...(fetchOptions.headers as Record<string, string>),
  };

  if (token) {
    headers["Authorization"] = `Bearer ${token}`;
  }

  if (fetchOptions.body && typeof fetchOptions.body === "string") {
    headers["Content-Type"] = "application/json";
  }

  // Idempotency for mutating requests: a stable key lets the backend's
  // idempotency middleware dedupe retries (fetchWithRetry may replay 5xx /
  // network failures) so a single user action never mutates state twice.
  // The key is generated once per request() call and reused across retries.
  const method = (fetchOptions.method ?? "GET").toUpperCase();
  if (
    (method === "POST" || method === "PUT" || method === "PATCH") &&
    !headers["Idempotency-Key"]
  ) {
    headers["Idempotency-Key"] = crypto.randomUUID();
  }

  const res = await fetchWithRetry(
    `${API_URL}${path}`,
    { ...fetchOptions, headers },
    timeoutMs,
  );

  if (!res.ok) {
    const body = await parseErrorBody(res);
    throw new ApiClientError(res.status, body);
  }

  if (res.status === 204) {
    return undefined as T;
  }

  return res.json();
}

// ── API methods ──

async function uploadRequest<T>(
  path: string,
  token: string,
  formData: FormData,
): Promise<T> {
  const res = await fetchWithRetry(`${API_URL}${path}`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Idempotency-Key": crypto.randomUUID(),
    },
    body: formData,
  });

  if (!res.ok) {
    const body = await parseErrorBody(res);
    throw new ApiClientError(res.status, body);
  }

  return res.json();
}

/** A binary download with progress reporting and cancellation. */
export interface BinaryDownload {
  blob: Blob;
  filename: string;
}

/**
 * Fetch a binary attachment, reporting progress when the server sends a
 * Content-Length. Not routed through `fetchWithRetry`: a retry would restart a
 * potentially large transfer, and the caller owns cancellation via `signal`.
 */
async function downloadRequest(
  path: string,
  token: string,
  options?: {
    signal?: AbortSignal;
    onProgress?: (loaded: number, total: number | null) => void;
    fallbackFilename?: string;
  },
): Promise<BinaryDownload> {
  const res = await fetch(`${API_URL}${path}`, {
    headers: { Authorization: `Bearer ${token}` },
    signal: options?.signal,
  });

  if (!res.ok) {
    const body = await parseErrorBody(res);
    throw new ApiClientError(res.status, body);
  }

  const filename =
    parseContentDispositionFilename(res.headers.get("Content-Disposition")) ??
    options?.fallbackFilename ??
    "download";

  const lengthHeader = res.headers.get("Content-Length");
  const total = lengthHeader ? Number(lengthHeader) : null;

  if (!res.body || !options?.onProgress) {
    return { blob: await res.blob(), filename };
  }

  const reader = res.body.getReader();
  const chunks: Uint8Array[] = [];
  let loaded = 0;

  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    chunks.push(value);
    loaded += value.length;
    options.onProgress(loaded, Number.isFinite(total) ? total : null);
  }

  const type = res.headers.get("Content-Type") ?? "application/octet-stream";
  return { blob: new Blob(chunks as BlobPart[], { type }), filename };
}

function parseContentDispositionFilename(header: string | null): string | null {
  if (!header) return null;
  const quoted = header.match(/filename="([^"]+)"/i);
  if (quoted) return quoted[1];
  const bare = header.match(/filename=([^;]+)/i);
  return bare ? bare[1].trim() : null;
}

